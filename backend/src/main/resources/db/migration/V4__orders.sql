-- =====================================================================
-- V4: Pedidos (carrinho + checkout) de produtos de revenda (RESALE).
-- Um pedido (orders) pertence a um negócio e a um cliente (Supabase user),
-- e tem vários itens (order_items), cada um referenciando um item de estoque.
-- O preço é "congelado" no momento da compra (unit_price em order_items),
-- para o histórico não mudar se o dono reajustar o preço depois.
-- Compatível com PostgreSQL (Supabase) e H2 em modo PostgreSQL.
-- =====================================================================

CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id    BIGINT        NOT NULL,
    client_user_id VARCHAR(64)   NOT NULL,  -- Supabase user id do cliente
    client_name    VARCHAR(150)  NOT NULL,
    client_phone   VARCHAR(30),
    total          NUMERIC(10,2) NOT NULL DEFAULT 0,
    status         VARCHAR(20)   NOT NULL DEFAULT 'PENDING', -- PENDING | CONFIRMED | DELIVERED | CANCELLED
    notes          VARCHAR(500),
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_order_business FOREIGN KEY (business_id)
        REFERENCES businesses (id) ON DELETE CASCADE
);

CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT        NOT NULL,
    inventory_id  BIGINT,                   -- item de estoque (SET NULL se o produto for removido)
    product_name  VARCHAR(150)  NOT NULL,   -- nome congelado no momento da compra
    unit_price    NUMERIC(10,2) NOT NULL DEFAULT 0,
    quantity      INTEGER       NOT NULL DEFAULT 1,
    CONSTRAINT fk_item_order FOREIGN KEY (order_id)
        REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_inventory FOREIGN KEY (inventory_id)
        REFERENCES inventory_items (id) ON DELETE SET NULL
);

CREATE INDEX idx_orders_business ON orders (business_id);
CREATE INDEX idx_orders_client   ON orders (client_user_id);
CREATE INDEX idx_order_items_order ON order_items (order_id);
